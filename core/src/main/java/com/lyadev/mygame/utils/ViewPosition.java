package com.lyadev.mygame.utils;

public class ViewPosition {
    private final float x;
    private final float y;

    public ViewPosition(float x, float y) {
        this.x = x;
        this.y = y;
    }

    public float getX() {
        return x;
    }

    public float getY() {
        return y;
    }
}
